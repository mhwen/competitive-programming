using namespace std;
typedef long long ll;
typedef long double ld;
#define sz(x) (int)(x).size()
#define all(x) begin(x), end(x)

int main() {
	ios::sync_with_stdio(false);
	cin.tie(nullptr);
	int t;
	cin >> t;
	while(t-->0) {
		int n;
		cin >> n;
		vector<ll> nums(n);
		for(int i = 0; i < n; i++)
			cin >> nums[i];
		sort(all(nums));
		ll res = nums[0];
		for(int i = 1; i < sz(nums); i++) {
			res = (res+nums[i])/2;
		}
		cout << res << "\n";
	}
}